#!/bin/sh
# progeo-matrix: writes homeserver.yaml from the MATRIX_* variables of .env
# (Synapse reads no environment variables for these), creates the signing key
# on the first start and hands over to the image's own start script.
set -eu

for name in MATRIX_DOMAIN MATRIX_DB_PASSWORD MATRIX_MAS_SECRET MATRIX_MACAROON_SECRET MATRIX_FORM_SECRET; do
  eval "value=\${${name}:-}"
  if [ -z "${value}" ]; then
    echo "${name} is empty - set it in .env (docker/matrix/README.md)" >&2
    exit 1
  fi
done

config=/data/homeserver.yaml
umask 077

# MATRIX_FEDERATION=1: users of other homeservers (matrix.org, ...) can be
# reached and our users can join their rooms. Off by default - a closed
# server for ProGeo's own accounts has far less to attack.
if [ "${MATRIX_FEDERATION:-0}" = "1" ]; then
  resources='[client, federation]'
  federation='trusted_key_servers:
  - server_name: matrix.org
suppress_key_server_warning: true
allow_public_rooms_over_federation: false'
else
  resources='[client]'
  federation='# No federation: no server is allowed, no keys are fetched from anywhere.
federation_domain_whitelist: []
trusted_key_servers: []'
fi

# The Signal bridge's appservice registration (progeo-signal-bridge-init).
appservices='app_service_config_files: []'
if [ -f /bridges/signal/registration.yaml ]; then
  appservices='app_service_config_files:
  - /bridges/signal/registration.yaml'
fi

cat > "$config" <<EOF
# Generated by docker/matrix/entrypoint.sh on every start - edit that file.
# server_name is part of every user and room ID: never change it later.
server_name: '${MATRIX_DOMAIN}'
public_baseurl: 'https://${MATRIX_DOMAIN}/'
pid_file: /data/homeserver.pid
report_stats: false

# Plain HTTP behind progeo-nginx, which terminates TLS (and exposes only the
# client API, plus federation with MATRIX_FEDERATION=1).
listeners:
  - port: 8008
    type: http
    tls: false
    x_forwarded: true
    bind_addresses: ['0.0.0.0']
    resources:
      - names: ${resources}
        compress: false

database:
  name: psycopg2
  args:
    user: synapse
    password: '${MATRIX_DB_PASSWORD}'
    dbname: synapse
    host: progeo-matrix-db
    cp_min: 2
    cp_max: 10

log_config: /config/log.config
media_store_path: /data/media_store
signing_key_path: '/data/${MATRIX_DOMAIN}.signing.key'
${federation}

# Logins and accounts belong to the Matrix Authentication Service
# (progeo-mas, mas_init.py): it signs users in through the ProGeo portal and
# creates their account on the first login. No guests, no identity servers.
matrix_authentication_service:
  enabled: true
  endpoint: 'http://progeo-mas:8080/'
  secret: '${MATRIX_MAS_SECRET}'
enable_registration: false
allow_guest_access: false
enable_3pid_lookup: false
macaroon_secret_key: '${MATRIX_MACAROON_SECRET}'
form_secret: '${MATRIX_FORM_SECRET}'

${appservices}

# Nobody learns about users or rooms they don't share a room with.
require_auth_for_profile_requests: true
limit_profile_requests_to_users_who_share_rooms: true
include_profile_data_on_invite: false
user_directory:
  enabled: true
  search_all_users: false
allow_public_rooms_without_auth: false
room_list_publication_rules:
  - action: deny
alias_creation_rules:
  - action: deny

# ProGeo only sends text: small uploads, media only with a login, no link
# previews (they would make the server fetch arbitrary URLs).
max_upload_size: 10M
enable_authenticated_media: true
url_preview_enabled: false
dynamic_thumbnails: false
enable_metrics: false
EOF

python -m synapse.app.homeserver --config-path "$config" --keys-directory /data --generate-keys
# start.py runs Synapse as UID/GID 991.
chown -R 991:991 /data

exec /start.py "$@"
