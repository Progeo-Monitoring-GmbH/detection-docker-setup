"""progeo-matrix-init: prepares the Matrix Authentication Service (MAS).

Runs once per `docker compose up` in the Synapse image (Python, psycopg2 and
cryptography are there; the MAS image has no shell):
  - creates the role and database "mas" in progeo-matrix-db,
  - creates MAS's signing key on the first run (/mas/keys/rsa.pem),
  - writes /mas/config.yaml from the MATRIX_* / PORTAL_OIDC_* variables of .env.

Logins: MAS has no passwords of its own. Its only login is the ProGeo portal
(OpenID Connect, progeo/oidc.py), so every portal user gets a Matrix account
on the first login - and nobody else does.
"""
import os
import sys
import time

import psycopg2
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa
from psycopg2 import sql

# Upstream provider "ProGeo" - must stay the same: MAS links accounts to it,
# and the portal's redirect URI contains it (manage.py matrix_oidc_client).
PROGEO_PROVIDER_ID = "01M6GBK9WNWPFWH861CMP1EMFX"
MAS_UID = 65532  # the user of the MAS image
REQUIRED = ("MATRIX_DOMAIN", "MATRIX_AUTH_DOMAIN", "MATRIX_DB_PASSWORD", "MATRIX_MAS_DB_PASSWORD",
            "MATRIX_MAS_SECRET", "MATRIX_MAS_ENCRYPTION", "PORTAL_OIDC_ISSUER", "MATRIX_OIDC_CLIENT_SECRET")


def env(name):
    return os.environ.get(name, "").strip()


def create_database():
    for attempt in range(30):
        try:
            connection = psycopg2.connect(host="progeo-matrix-db", user="synapse", dbname="synapse",
                                          password=env("MATRIX_DB_PASSWORD"))
            break
        except psycopg2.OperationalError as exc:
            print(f"waiting for progeo-matrix-db ({exc.__class__.__name__})", flush=True)
            time.sleep(2)
    else:
        sys.exit("progeo-matrix-db is not reachable")
    connection.autocommit = True
    with connection.cursor() as cursor:
        cursor.execute("SELECT 1 FROM pg_roles WHERE rolname = 'mas'")
        verb = "ALTER" if cursor.fetchone() else "CREATE"
        cursor.execute(sql.SQL(verb + " ROLE mas LOGIN PASSWORD {}").format(sql.Literal(env("MATRIX_MAS_DB_PASSWORD"))))
        cursor.execute("SELECT 1 FROM pg_database WHERE datname = 'mas'")
        if not cursor.fetchone():
            cursor.execute("CREATE DATABASE mas OWNER mas ENCODING 'UTF8' TEMPLATE template0")
            print("created database mas", flush=True)
    connection.close()


def create_key(path):
    if os.path.exists(path):
        return
    key = rsa.generate_private_key(public_exponent=65537, key_size=4096)
    with open(path, "wb") as handle:
        handle.write(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                                       serialization.NoEncryption()))
    print("created the MAS signing key", flush=True)


def config():
    domain, auth = env("MATRIX_DOMAIN"), env("MATRIX_AUTH_DOMAIN")
    return f"""# Generated by docker/matrix/mas_init.py on every start - edit that file.
http:
  public_base: 'https://{auth}/'
  listeners:
    - name: web
      resources:
        - name: discovery
        - name: human
        - name: oauth
        - name: compat
        - name: graphql
        - name: assets
      binds:
        - address: '[::]:8080'

database:
  uri: 'postgresql://mas:{env("MATRIX_MAS_DB_PASSWORD")}@progeo-matrix-db/mas'

matrix:
  kind: synapse
  homeserver: '{domain}'
  endpoint: 'http://progeo-matrix:8008/'
  secret: '{env("MATRIX_MAS_SECRET")}'

secrets:
  encryption: '{env("MATRIX_MAS_ENCRYPTION")}'
  keys:
    - key_file: /mas/keys/rsa.pem

# No passwords and no sign-up in MAS: the ProGeo portal is the only login.
passwords:
  enabled: false
account:
  password_registration_enabled: false
  password_change_allowed: false
  email_change_allowed: false
  displayname_change_allowed: false
  account_deactivation_allowed: false

upstream_oauth2:
  providers:
    - id: '{PROGEO_PROVIDER_ID}'
      human_name: ProGeo
      issuer: '{env("PORTAL_OIDC_ISSUER")}'
      client_id: progeo-matrix
      client_secret: '{env("MATRIX_OIDC_CLIENT_SECRET")}'
      token_endpoint_auth_method: client_secret_basic
      scope: 'openid profile'
      pkce_method: always
      # The portal's login form gets the name from the QR code's login link.
      forward_login_hint: true
      claims_imports:
        # progeo/helper/matrix_accounts.py matrix_localpart(): unique, valid.
        localpart:
          action: require
          template: '{{{{ user.preferred_username }}}}'
        displayname:
          action: force
          template: '{{{{ user.name }}}}'
        email:
          action: ignore
        skip_confirmation: true
"""


def main():
    missing = [name for name in REQUIRED if not env(name)]
    if missing:
        sys.exit(f"empty in .env: {', '.join(missing)} (docker/matrix/README.md)")
    os.umask(0o077)
    os.makedirs("/mas/keys", exist_ok=True)
    create_database()
    create_key("/mas/keys/rsa.pem")
    with open("/mas/config.yaml", "w") as handle:
        handle.write(config())
    for root, dirs, files in os.walk("/mas"):
        for name in [*dirs, *files]:
            os.chown(os.path.join(root, name), MAS_UID, MAS_UID)
    os.chown("/mas", MAS_UID, MAS_UID)
    print("MAS config written", flush=True)


if __name__ == "__main__":
    main()
